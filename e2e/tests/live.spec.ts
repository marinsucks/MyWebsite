import { test, expect } from '@playwright/test';
import { checkRecentDeliveries, resendGet } from '../provider-monitor.mjs';

const domain = process.env.MONITOR_DOMAIN;
if (!domain || !/^[a-z0-9.-]+$/.test(domain)) throw new Error('MONITOR_DOMAIN must be a hostname');
const options = { domain, apiKey: process.env.RESEND_MONITOR_API_KEY || process.env.RESEND_API_KEY };

test('production pages, API and the production Turnstile secret are reachable', async ({ page, request }) => {
  for (const path of ['/', '/work', '/about', '/contact']) {
    const response = await page.goto(`https://${domain}${path}`);
    expect(response?.status()).toBe(200);
    await expect(page.getByRole('heading', { level: 1 })).toBeVisible();
  }
  await expect(page.locator('iframe[src*="challenges.cloudflare.com"]')).toBeAttached();
  const health = await request.get(`https://${domain}/api/health`);
  expect(health.status()).toBe(200);
  expect(await health.json()).toMatchObject({ status: 'ok' });
  // Invalid visitor token: must be rejected. Provider/secret problems must be 503,
  // not misreported as a normal rejected challenge. No real email can be sent.
  const rejected = await request.post(`https://${domain}/api/contact`, { data: {
    name: 'Portfolio monitor', email: 'delivered+portfolio-monitor-visitor@resend.dev',
    subject: 'Monitoring challenge rejection', message: 'Synthetic provider availability check.',
    locale: 'en', turnstileToken: 'monitor-intentionally-invalid-token', submissionId: crypto.randomUUID(),
  } });
  expect(rejected.status()).toBe(403);
  expect(await rejected.json()).toMatchObject({ error: { code: 'CHALLENGE_FAILED' } });
});

test('the form passes real Turnstile verification and Resend accepts and delivers both test emails', async ({ page, request }) => {
  // Official Cloudflare test widget, real Cloudflare Siteverify, real Resend API.
  // No page.route(), network mocking or production CAPTCHA bypass.
  await page.goto('/contact');
  await page.locator('[name=name]').fill('Portfolio monitor');
  await page.locator('[name=email]').fill('delivered+portfolio-monitor-visitor@resend.dev');
  await page.locator('[name=subject]').fill('Automated contact health check');
  await page.locator('[name=message]').fill('Synthetic test generated by the portfolio monitor. No action needed.');
  await expect(page.locator('button[type=submit]')).toBeEnabled({ timeout: 45_000 });
  const response = page.waitForResponse('**/api/contact');
  await page.locator('button[type=submit]').click();
  expect((await response).status()).toBe(202);
  await expect(page.getByRole('status')).toBeVisible();
  const { receipts } = await (await request.get('http://127.0.0.1:4174/state')).json();
  expect(receipts).toHaveLength(1);
  for (const id of [receipts[0].notificationId, receipts[0].confirmationId]) {
    expect(typeof id).toBe('string');
    await expect.poll(async () => (await resendGet(`/emails/${id}`, options)).last_event,
      { timeout: 45_000, intervals: [1500, 3000, 5000] }).toBe('delivered');
  }
});

test('recent production messages have no failed or overdue delivery', async () => {
  await checkRecentDeliveries(options);
});
